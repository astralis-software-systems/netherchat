// tomlString renders s as a TOML basic string, escaping the only two characters
// that matter inside one (backslash and double-quote).
func tomlString(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, `"`, `\"`)
	return `"` + s + `"`
}
